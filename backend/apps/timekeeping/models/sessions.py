from django.conf import settings
from django.contrib.postgres.fields import ArrayField
from django.db import models
from django.db.models import Q
from django.utils import timezone

from .choices import PunchType, ReviewDecision, ReviewStatus, SessionExceptionFlag, SessionStatus


class WorkSession(models.Model):
    """One employee's attendance on one job, from clock-in to clock-out.

    Authorised by a job assignment (which identifies the employee and job).
    ``work_date`` is derived from the clock-in instant in the company
    timezone (ADR 008). Location exceptions set ``review_status`` to pending.
    """

    assignment = models.ForeignKey(
        "jobs.JobAssignment", on_delete=models.PROTECT, related_name="work_sessions"
    )
    work_date = models.DateField()
    session_status = models.CharField(
        max_length=16, choices=SessionStatus.choices, default=SessionStatus.OPEN
    )
    review_status = models.CharField(
        max_length=16, choices=ReviewStatus.choices, default=ReviewStatus.NOT_REQUIRED
    )
    reviewed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="reviewed_work_sessions",
    )
    reviewed_at = models.DateTimeField(null=True, blank=True)
    # Why the session needs review; a set kept sorted and free of duplicates by
    # services.sessions.add_exception_flags. Never cleared by a review.
    exception_flags = ArrayField(
        models.CharField(max_length=32, choices=SessionExceptionFlag.choices),
        default=list,
        blank=True,
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ("-work_date", "-created_at")
        constraints = [
            models.UniqueConstraint(
                fields=("assignment",),
                condition=Q(session_status=SessionStatus.OPEN),
                name="timekeeping_session_one_open_per_assignment",
            ),
            models.CheckConstraint(
                condition=Q(reviewed_by__isnull=True, reviewed_at__isnull=True)
                | Q(reviewed_by__isnull=False, reviewed_at__isnull=False),
                name="timekeeping_session_reviewer_and_time_together",
            ),
            models.CheckConstraint(
                condition=~Q(review_status__in=(ReviewStatus.APPROVED, ReviewStatus.REJECTED))
                | Q(reviewed_by__isnull=False),
                name="timekeeping_session_decision_requires_reviewer",
            ),
        ]
        indexes = [models.Index(fields=("work_date", "review_status"))]

    def __str__(self) -> str:
        return f"{self.assignment} on {self.work_date}"


class TimePunch(models.Model):
    """An immutable clock-in or clock-out for one employee, generated by a batch item.

    The punch instant is the batch's ``captured_at``.
    """

    session = models.ForeignKey(WorkSession, on_delete=models.PROTECT, related_name="punches")
    batch_item = models.OneToOneField(
        "timekeeping.AttendanceBatchItem", on_delete=models.PROTECT, related_name="time_punch"
    )
    punch_type = models.CharField(max_length=16, choices=PunchType.choices)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=("session", "punch_type"), name="timekeeping_punch_one_type_per_session"
            ),
        ]

    def __str__(self) -> str:
        return f"{self.get_punch_type_display()} ({self.session})"


class WorkSessionReview(models.Model):
    """Append-only audit log of review decisions on a work session.

    Each decision adds a row; rows are never updated or deleted. The session's
    review_status / reviewed_by / reviewed_at mirror the latest row.
    """

    session = models.ForeignKey(WorkSession, on_delete=models.PROTECT, related_name="reviews")
    decision = models.CharField(max_length=16, choices=ReviewDecision.choices)
    reason = models.TextField()
    reviewed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="work_session_reviews"
    )
    reviewed_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ("-reviewed_at", "-id")
        constraints = [
            models.CheckConstraint(
                condition=~Q(reason__regex=r"^\s*$"), name="timekeeping_review_reason_required"
            ),
        ]

    def __str__(self) -> str:
        return f"{self.get_decision_display()} by {self.reviewed_by} ({self.session})"

    def save(self, *args, **kwargs) -> None:
        if self.pk is not None:
            raise ValueError("Work session reviews are append-only and cannot be modified.")
        super().save(*args, **kwargs)

    def delete(self, *args, **kwargs):
        raise ValueError("Work session reviews are append-only and cannot be deleted.")
